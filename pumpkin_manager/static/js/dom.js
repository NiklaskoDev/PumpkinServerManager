// Tiny DOM helpers. Text is always inserted as text nodes, never parsed as markup, so untrusted
// content (player chat, file names, server output) cannot inject HTML. The one innerHTML use is the
// static icon table below, which is trusted source code.

const SVG_NS = "http://www.w3.org/2000/svg";

function appendChildren(parent, children) {
  for (const child of children) {
    if (child == null || child === false || child === true) continue;
    if (Array.isArray(child)) appendChildren(parent, child);
    else if (child instanceof Node) parent.appendChild(child);
    else parent.appendChild(document.createTextNode(String(child)));
  }
}

export function h(tag, props, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props || {})) {
    if (value == null || value === false) continue;
    if (key === "class") el.className = value;
    else if (key === "style" && typeof value === "object") Object.assign(el.style, value); // CSSOM: allowed under CSP
    else if (key === "dataset") Object.assign(el.dataset, value);
    else if (key.startsWith("on") && typeof value === "function") el.addEventListener(key.slice(2).toLowerCase(), value);
    else if (key === "for") el.htmlFor = value;
    else if (["value", "checked", "disabled", "selected", "readOnly", "multiple", "indeterminate"].includes(key)) el[key] = value;
    else el.setAttribute(key, value === true ? "" : value);
  }
  appendChildren(el, children);
  return el;
}

export function svgEl(tag, attrs = {}, ...children) {
  const el = document.createElementNS(SVG_NS, tag);
  for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);
  for (const child of children) if (child) el.appendChild(child);
  return el;
}

export function clear(el) {
  while (el.firstChild) el.removeChild(el.firstChild);
  return el;
}

export function replaceChildren(el, ...children) {
  clear(el);
  appendChildren(el, children);
  return el;
}

